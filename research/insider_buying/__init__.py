"""Offline, non-executing contracts for the Insider Buying research lane.

This package deliberately has no network collection, outcome, portfolio,
broker, or scheduler surface. It contains immutable in-memory Form 4
structure, a fixture parser, and a caller-supplied SEC quarterly ZIP integrity
boundary plus explicit-profile, offline parsed, EDGAR acceptance-evidence, and
observation-only Form 4/A chronology and multi-period supplied-link-evidence
boundaries, plus an evidence-bound provisional disposition/quarantine report
and its immutable, upstream-rebuilt snapshot boundary.  The package also
exposes the zero-authority IB-1I four-family research gate without allocating
a confirmatory cell or permanent look, plus the observed-only IB-2A normalized
identity inventory that leaves every point-in-time resolution gate closed.
It also exposes the IB-2B exact-SEC-CIK grouping boundary, which retains every
issuer and reporting-owner observation and quarantines ambiguous attribution.
The IB-2C boundary maps those exhaustive transactions against caller-supplied,
dated security/title/ticker references while retaining zero external authority.
IB-2D adds exhaustive provisional lot diagnostics and an exact USD 50,000
comparison while retaining every downstream authority gate as false.
IB-3A adds synthetic-only event-size, freshness, raw-score, and breadth
equation diagnostics; it does not consume IB-2D or expose a canonical score.
IB-3B adds an exhaustive caller-declared synthetic cohort plus frozen
winsorization and population-z-score diagnostics while keeping canonical
scores, ranks, seeds, outcomes, and every operational authority unavailable.
IB-3C adds exact-value diagnostic ranking, top-decile cutoff ties, and a
two-positive-seed availability gate while retaining the same zero authority.
IB-3D preserves that selection and applies a separate, caller-declared buyer-
breadth gate, atomically refusing fewer than two cluster-qualified stocks.
The canonical IB-2 source policy freezes an owner-supplied, offline 82-quarter
input requirement while keeping every real artifact and authority unbound.
The synthetic-only source-manifest boundary validates caller-supplied byte
streams and ordered 82-quarter identity claims without reading real artifacts
or declaring canonical completeness.
The explicit v2 source-policy/manifest epoch retains 3/A and 5/A as context
only while preserving the frozen v1 policy and its reproducible manifest.
"""

